CONTEXT = []          # функции без аргументов → строка контекста (или ""); их регистрируют плагины


def _context_block():
    out = []
    for f in CONTEXT:
        try:
            t = f()
        except Exception:
            t = ""
        if t:
            out.append(t)
    return "".join("\n\n" + t for t in out)


