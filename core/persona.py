def custom_text():
    """Свой промпт с подстановкой имён. Фигурные скобки в нём — не наши поля, поэтому replace, а не .format()."""
    name, user, address = config["assistant_name"], config["user_name"] or "пользователь", config["address"]
    return config["persona_custom"].replace("{name}", name).replace("{user}", user).replace("{address}", address)


def character_reminder():
    """Характер — ещё раз последним словом перед ответом: модели слушают конец промпта сильнее начала."""
    if config["persona"] == "custom" and config["persona_custom"].strip():
        return "Твой характер (главное — держи его в этом ответе полностью):\n" + custom_text() + "\n\n"
    if config["persona"] == "kitsune":
        return "Твой характер: цундере-кицунэ из промпта выше — держи его во всём ответе.\n\n"
    return ""


def persona_hash():
    import hashlib
    return hashlib.sha1("|".join([config["persona"], config.get("persona_custom", ""), config["assistant_name"],
                                  config["address"]]).encode("utf-8")).hexdigest()[:12]


def persona_since():
    """Когда сменился характер. Старые ответы в прежнем стиле в контекст не берём — модель копирует их тон сильнее промпта."""
    import json, time
    from .config import DATA
    f = DATA / "persona_rev.json"
    try:
        d = json.loads(f.read_text(encoding="utf-8"))
    except Exception:
        d = {}
    h = persona_hash()
    if d.get("hash") != h:
        d = {"hash": h, "since": time.time()}          # и при первом запуске: прежние ответы писались по-старому
        f.write_text(json.dumps(d), encoding="utf-8")
    return d["since"]


def system_prompt(voice=False):
    name, user, address = config["assistant_name"], config["user_name"] or "пользователь", config["address"]
    kind = config["persona"]
    # характер, который задал человек, — без правок; встроенные — с подстановкой полей
    now = dt.datetime.now()
    if kind == "custom" and config["persona_custom"].strip():
        text = CUSTOM_PREFACE + custom_text()
    else:
        text = (KITSUNE if kind == "kitsune" else NEUTRAL).format(name=name, user=user, address=address)
    text += RULES.format(
        user=user, address=address, now=now.strftime("%Y-%m-%d %H:%M"), weekday=WEEKDAYS[now.weekday()])
    from . import creator, friendship
    text += _place() + _facts_block() + friendship.tone_line() + creator.tone_line()   # тон — только характеру
    if voice:
        text += VOICE_RULES
    return text + lang_rule()


