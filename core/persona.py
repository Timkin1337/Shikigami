def stage_directions(text):
    return re.findall(r"\*([^*\n]{2,120})\*", text)


EMO_TAG = re.compile(r"\s*\[(happy|shy|angry|sad|surprised|relaxed|neutral)\]\s*$", re.I)
ANY_TAG = re.compile(r"\s*\[[a-z_]{2,15}\]\s*$", re.I)   # модель иногда выдумывает метку не из списка («[smile]») — тоже снимаем


def named(text):
    """Заготовки, описания и подсказки написаны с меткой {name} — подставляем имя, выбранное в настройках
    (до мастера первого запуска имени нет — тогда название программы)."""
    if not text:
        return text
    return text.replace("{name}", (config.get("assistant_name") or "").strip() or "Shikigami")


def lang_rule():
    """Инструкции модели написаны по-русски; на другом языке программы — велим отвечать на нём."""
    from .i18n import lang
    return "" if lang() == "ru" else ("\n\nIMPORTANT: the user speaks English. Always reply in natural English, "
                                      "even though these instructions are in Russian. Address the user as "
                                      "\"Master\" where the instructions say «господин».")


def clean(text):
    """Что показываем и говорим: без ремарок в звёздочках, без заиканий «Н-не», без метки эмоции."""
    from .i18n import tr
    t = named(tr(ANY_TAG.sub("", EMO_TAG.sub("", text or "")).strip()))
    t = re.sub(r"\*\*([^*\n]+)\*\*", r"\1", t)    # жирный **…** — это не ремарка: иначе от него оставались «* *»
    t = re.sub(r"\*[^*\n]{1,160}\*", " ", t)
    # «Н-не», «Ч-что», «С-спасибо» → «Не», «Что», «Спасибо» (буква, дефис, слово на ту же букву)
    t = re.sub(r"(?<![\w-])([А-ЯЁа-яё])-([А-ЯЁа-яё])",
               lambda m: m.group(1) if m.group(1).lower() == m.group(2).lower() else m.group(0), t)
    t = re.sub(r"[ \t]{2,}", " ", t)
    # «... ...» от вырезанной ремарки между двумя многоточиями — одно многоточие
    t = re.sub(r"(\.{3}|…)\s+(?:\.{3}|…)", r"\1 ", t)
    # перед многоточием («…» и «...») пробел оставляем: «Ну что вы? …Ладно», иначе выходило «out....Not»
    t = re.sub(r"\s+([,!?]|\.(?!\.))", r"\1", t)
    return t.strip()


def emotion_of(text):
    m = EMO_TAG.search(text or "")
    if m:
        return m.group(1).lower()
    acts = " ".join(stage_directions(text)).lower() or text.lower()[:200]
    for emo, pat in EMOTION_RULES:
        if re.search(pat, acts):
            return emo
    return "neutral"


def speech_text(text):
    """Что озвучивать: без ремарок, разметки, ссылок и кода."""
    t = re.sub(r"```.*?```", " ", text, flags=re.S)
    t = re.sub(r"\*[^*\n]{1,160}\*", " ", t)
    t = re.sub(r"https?://\S+", " ", t)
    t = re.sub(r"[`#>|_~]", " ", t)
    t = re.sub(r"^\s*[-•]\s*", "", t, flags=re.M)
    t = re.sub(r"\s+", " ", t).strip()
    return t
