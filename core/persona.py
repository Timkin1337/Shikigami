def for_executor(history):
    """Исполнителю ремарки в прошлых ответах только мешают — он начинает их продолжать."""
    out = []
    for m in history:
        if m["role"] == "assistant" and m.get("content"):
            m = dict(m, content=re.sub(r"\*[^*\n]{1,160}\*", "", m["content"]).strip())
        out.append(m)
    return out


